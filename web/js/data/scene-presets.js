  function getScenePreset(sceneId) {
    return scenePresets.find((scene) => scene.id === sceneId) || scenePresets[0];
  }

  function sceneSupportsMode(scene, mode) {
    if (!scene) return false;
    if (mode === MODE_DEFAULT) return Boolean(scene.isHome);
    return (scene.modes || [MODE_DEFAULT]).includes(mode);
  }

  function getScenesForMode(mode) {
    if (mode === MODE_DEFAULT) return scenePresets.filter((scene) => scene.isHome);
    const scenes = scenePresets.filter((scene) => sceneSupportsMode(scene, mode));
    return scenes.length ? scenes : scenePresets;
  }

  function getMissingBackgroundScenes() {
    return scenePresets.filter((scene) => scene.backgroundMissing);
  }

